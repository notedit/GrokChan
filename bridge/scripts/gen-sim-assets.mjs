#!/usr/bin/env node
// Generates src/sim/assets.gen.ts from the web device sources, so the bridge's /sim route serves
// byte-identical copies of what `firmware/tools/webdevice/serve.mjs` serves (no forked UI).
//   npm run gen:sim          (re-run after changing anything under firmware/tools/webdevice/web
//                             or firmware/tools/preview/face_draw.js; test/sim.unit.test.ts fails when stale)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..", "..", "firmware", "tools");
const FILES = [
  ["index.html", join(root, "webdevice", "web", "index.html"), "text/html; charset=utf-8"],
  ["style.css", join(root, "webdevice", "web", "style.css"), "text/css; charset=utf-8"],
  ["app.js", join(root, "webdevice", "web", "app.js"), "text/javascript; charset=utf-8"],
  ["device.js", join(root, "webdevice", "web", "device.js"), "text/javascript; charset=utf-8"],
  ["mic-worklet.js", join(root, "webdevice", "web", "mic-worklet.js"), "text/javascript; charset=utf-8"],
  ["face_draw.js", join(root, "preview", "face_draw.js"), "text/javascript; charset=utf-8"],
  ["gc_core.wasm", join(root, "webdevice", "web", "gc_core.wasm"), "application/wasm"],
];

export const OUT = join(here, "..", "src", "sim", "assets.gen.ts");

export function buildAssetsSource() {
  const entries = FILES.map(([name, file, type]) => {
    const buf = readFileSync(file);
    const binary = name.endsWith(".wasm");
    return `  ${JSON.stringify("/" + name)}: { type: ${JSON.stringify(type)}, binary: ${binary}, body: ${JSON.stringify(binary ? buf.toString("base64") : buf.toString("utf8"))} },`;
  });
  return (
    "// GENERATED by scripts/gen-sim-assets.mjs - do not edit. Sources: firmware/tools/webdevice/web/*, firmware/tools/preview/face_draw.js\n" +
    "export interface SimAsset { type: string; binary: boolean; body: string }\n" +
    "export const SIM_ASSETS: Record<string, SimAsset> = {\n" + entries.join("\n") + "\n};\n"
  );
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, buildAssetsSource());
  console.log("wrote", OUT);
}
