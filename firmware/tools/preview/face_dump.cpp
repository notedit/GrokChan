// Desktop preview data generator (no hardware): runs the SAME gc::FaceAnimator as the device and
// dumps its FaceFrames as a JS data file that tools/preview/preview.html draws with Canvas.
//   face_dump <out.js>
// Build / run / screenshots: tools/preview/run_preview.sh
#include <cmath>
#include <cstdio>
#include <string>
#include <vector>
#include "gc_face.h"

using namespace gc;

static FILE* out = nullptr;

static void dumpFrame(const FaceFrame& f) {
  fprintf(out, "{\"bg\":%u,\"accent\":%u,\"p\":[", f.bg, f.accent);
  for (int i = 0; i < f.nPrims; i++) {
    const FacePrim& p = f.prims[i];
    fprintf(out, "%s[%d,%u,%.1f,%.1f,%.1f,%.1f,%.1f,", i ? "," : "", (int)p.type, p.color, p.x, p.y, p.rx, p.ry, p.thick);
    if (p.type == PrimType::Poly) {
      fprintf(out, "[");
      for (int k = 0; k < p.n; k++) fprintf(out, "%s%.1f,%.1f", k ? "," : "", f.pts[p.off + k].x, f.pts[p.off + k].y);
      fprintf(out, "]");
    } else {
      fprintf(out, "0");
    }
    fprintf(out, "]");
  }
  fprintf(out, "]}");
}

// level hint like a talking voice: slow syllable envelope
static float level(uint32_t t) { return 0.45f + 0.4f * sinf(t * 0.011f) * sinf(t * 0.0037f); }

struct Run {
  FaceAnimator a;
  uint32_t t = 1000;
  bool lvl = false;
  Run() { a.reset(t, 12345); a.update(t); }
  void step(uint32_t ms, uint32_t dt = 50) {
    for (uint32_t d = 0; d < ms; d += dt) {
      t += dt;
      if (lvl) a.setLevel(level(t));
      a.update(t);
    }
  }
  // advance until the character is not mid-blink (stills look better with open eyes unless the state
  // has closed eyes anyway; the limit makes this terminate)
  void openEyes() { for (int i = 0; i < 40 && a.debug().blink > 0.05f; i++) step(50); }
};

static const char* kStates[] = {"idle", "listening", "thinking", "speaking"};
static const FaceExpr kExprs[] = {FaceExpr::Neutral, FaceExpr::Happy, FaceExpr::Sad, FaceExpr::Angry, FaceExpr::Surprised, FaceExpr::Sleepy,
                                  FaceExpr::Thinking, FaceExpr::Confused, FaceExpr::Love, FaceExpr::Wink, FaceExpr::Speaking};

static void timeline(const char* key, bool exprs) {
  const uint32_t fpsMs = exprs ? 66 : 50;
  Run r;
  r.lvl = true;
  struct Seg { std::string label; uint32_t from; };
  std::vector<Seg> segs;
  std::string frames;
  fprintf(out, "%s:{\"fps\":%d,\"frames\":[", key, (int)lroundf(1000.0f / fpsMs));
  int n = 0;
  auto emit = [&](uint32_t ms) {
    uint32_t t0 = r.t;
    for (uint32_t d = 0; d < ms; d += fpsMs) {
      r.step(fpsMs, fpsMs);
      fprintf(out, "%s", n++ ? "," : "");
      dumpFrame(r.a.frame());
    }
    (void)t0;
  };
  uint32_t elapsed = 0;
  if (!exprs) {
    const char* seq[] = {"idle", "listening", "thinking", "speaking", "idle"};
    for (const char* s : seq) {
      segs.push_back({s, elapsed});
      r.a.setTurnState(s);
      emit(3500);
      elapsed += 3500;
    }
  } else {
    for (FaceExpr e : kExprs) {
      segs.push_back({faceExprName(e), elapsed});
      r.a.setExpression(e, r.t);
      emit(2400);
      elapsed += 2400;
    }
    segs.push_back({"neutral", elapsed});
    r.a.clearExpression();
    emit(1500);
    elapsed += 1500;
  }
  fprintf(out, "],\"segs\":[");
  for (size_t i = 0; i < segs.size(); i++) fprintf(out, "%s{\"label\":\"%s\",\"from\":%u}", i ? "," : "", segs[i].label.c_str(), segs[i].from);
  fprintf(out, "]}");
}

int main(int argc, char** argv) {
  if (argc < 2) { fprintf(stderr, "usage: face_dump <out.js>\n"); return 2; }
  out = fopen(argv[1], "w");
  if (!out) { perror("open"); return 1; }
  int bad = 0;
  fprintf(out, "// generated by tools/preview/face_dump.cpp - do not edit\nwindow.FACE = {\n");

  // --- four turn states (still frames after the spring settled)
  fprintf(out, "states:[");
  for (int i = 0; i < 4; i++) {
    Run r; r.lvl = true;
    r.a.setTurnState(kStates[i]);
    r.step(3000); r.openEyes();
    if (r.a.frame().dropped) bad++;
    fprintf(out, "%s{\"name\":\"%s\",\"frame\":", i ? "," : "", kStates[i]);
    dumpFrame(r.a.frame());
    fprintf(out, "}");
  }
  fprintf(out, "],\n");

  // --- all expressions as overlay on the idle turn state, plus one on another base to show coexistence
  fprintf(out, "exprs:[");
  int ne = 0;
  for (FaceExpr e : kExprs) {
    Run r; r.lvl = true;
    r.a.setExpression(e, r.t);
    r.step(3000);
    if (e != FaceExpr::Wink && e != FaceExpr::Sleepy) r.openEyes();
    if (r.a.frame().dropped) bad++;
    fprintf(out, "%s{\"name\":\"%s\",\"label\":\"%s\",\"frame\":", ne++ ? "," : "", faceExprName(e), faceExprName(e));
    dumpFrame(r.a.frame());
    fprintf(out, "}");
  }
  {
    Run r; r.lvl = true;
    r.a.setTurnState("listening");
    r.a.setExpression(FaceExpr::Love, r.t);
    r.step(3000); r.openEyes();
    fprintf(out, ",{\"name\":\"listening+love\",\"label\":\"listening + love\",\"frame\":");
    dumpFrame(r.a.frame());
    fprintf(out, "}");
  }
  fprintf(out, "],\n");

  // --- subtitle layouts (the character gives way); text box geometry mirrors pf_display.h
  fprintf(out, "layouts:[");
  struct L { const char* name; FaceTextLayout l; int y0; };
  const int lines = 3, bh = lines * 18 + 12;
  L ls[] = {{"top", FaceTextLayout::Top, 4}, {"center", FaceTextLayout::Center, (240 - bh) / 2}, {"bottom", FaceTextLayout::Bottom, 240 - bh - 4}};
  for (int i = 0; i < 3; i++) {
    Run r; r.lvl = true;
    r.a.setTurnState("speaking");
    r.a.setTextLayout(ls[i].l);
    r.step(3000); r.openEyes();
    if (r.a.frame().dropped) bad++;
    fprintf(out, "%s{\"name\":\"%s\",\"box\":[4,%d,312,%d],\"text\":[\"你好，我是 Grok，今天想聊点什么？\",\"字幕在上方 / 中间 / 下方时，\",\"角色会缩小并让位。\"],\"frame\":",
            i ? "," : "", ls[i].name, ls[i].y0, bh);
    dumpFrame(r.a.frame());
    fprintf(out, "}");
  }
  fprintf(out, "],\n");

  // --- transition strips: frames shortly after a state change
  fprintf(out, "strips:[");
  struct S { const char* from; const char* to; };
  S ss[] = {{"idle", "listening"}, {"listening", "thinking"}, {"thinking", "speaking"}, {"speaking", "idle"}};
  const uint32_t at[] = {0, 100, 200, 350, 600, 1000};
  for (int i = 0; i < 4; i++) {
    Run r; r.lvl = true;
    r.a.setTurnState(ss[i].from);
    r.step(3000); r.openEyes();
    r.a.setTurnState(ss[i].to);
    fprintf(out, "%s{\"label\":\"%s -> %s\",\"frames\":[", i ? "," : "", ss[i].from, ss[i].to);
    uint32_t done = 0;
    for (int k = 0; k < 6; k++) {
      if (at[k] > done) { r.step(at[k] - done); done = at[k]; }
      fprintf(out, "%s{\"t\":%u,\"frame\":", k ? "," : "", at[k]);
      dumpFrame(r.a.frame());
      fprintf(out, "}");
    }
    fprintf(out, "]}");
  }
  fprintf(out, "],\n");

  // --- animation timelines for the live page
  fprintf(out, "anim:{");
  timeline("turn", false);
  fprintf(out, ",");
  timeline("expr", true);
  fprintf(out, "}\n};\n");
  fclose(out);
  if (bad) { fprintf(stderr, "frame buffer overflow in %d scene(s)\n", bad); return 1; }
  return 0;
}
